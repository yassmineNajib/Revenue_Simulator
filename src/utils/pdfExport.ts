import jsPDF from 'jspdf';
import { SimulationResults, SimulationInputs, Language } from '../types';
import { formatCurrency, formatPercentage, generateRevenueProjection } from './calculations';
import { translations } from '../data/translations';

export const exportRevenueToPDF = async (
  results: SimulationResults,
  inputs: SimulationInputs,
  language: Language
) => {
  const t = translations[language];
  
  try {
    const pdf = new jsPDF('p', 'mm', 'a4');
    const pageWidth = pdf.internal.pageSize.getWidth();
    const pageHeight = pdf.internal.pageSize.getHeight();
    
    // Header
    pdf.setFillColor(30, 58, 138);
    pdf.rect(0, 0, pageWidth, 40, 'F');
    
    // Logo placeholder
    pdf.setFillColor(59, 130, 246);
    pdf.circle(25, 20, 8, 'F');
    
    // Title
    pdf.setTextColor(255, 255, 255);
    pdf.setFontSize(24);
    pdf.setFont('helvetica', 'bold');
    pdf.text('STOREINO', 40, 18);
    
    pdf.setFontSize(12);
    pdf.setFont('helvetica', 'normal');
    pdf.text('YOUR COMPANION TOWARDS LEADERSHIP', 40, 26);
    
    // Report title
    pdf.setFontSize(18);
    pdf.setFont('helvetica', 'bold');
    pdf.text(t.title, 20, 60);
    
    // Date
    pdf.setFontSize(10);
    pdf.setFont('helvetica', 'normal');
    pdf.setTextColor(100, 100, 100);
    const currentDate = new Date().toLocaleDateString(language === 'en' ? 'en-US' : 'fr-FR');
    pdf.text(`${language === 'en' ? 'Generated on:' : 'Généré le:'} ${currentDate}`, 20, 70);
    
    // Input Parameters Section
    pdf.setTextColor(30, 58, 138);
    pdf.setFontSize(16);
    pdf.setFont('helvetica', 'bold');
    pdf.text(language === 'en' ? 'Input Parameters' : 'Paramètres d\'Entrée', 20, 85);
    
    pdf.setTextColor(0, 0, 0);
    pdf.setFontSize(11);
    pdf.setFont('helvetica', 'normal');
    
    const inputData = [
      [t.form.monthlyVisitors, inputs.monthlyVisitors.toLocaleString()],
      [t.form.conversionRate, `${inputs.conversionRate}%`],
      [t.form.averageCartValue, formatCurrency(inputs.averageCartValue)],
      [t.form.storeinoFees, formatCurrency(inputs.storeinoFees)],
      [t.form.otherCosts, formatCurrency(inputs.otherCosts)]
    ];
    
    let yPos = 95;
    inputData.forEach(([label, value]) => {
      pdf.setFont('helvetica', 'bold');
      pdf.text(label + ':', 25, yPos);
      pdf.setFont('helvetica', 'normal');
      pdf.text(value, 120, yPos);
      yPos += 8;
    });
    
    // Results Section
    yPos += 10;
    pdf.setTextColor(30, 58, 138);
    pdf.setFontSize(16);
    pdf.setFont('helvetica', 'bold');
    pdf.text(t.results.title, 20, yPos);
    
    // Results box
    yPos += 10;
    pdf.setFillColor(248, 250, 252);
    pdf.rect(20, yPos, pageWidth - 40, 60, 'F');
    pdf.setDrawColor(30, 58, 138);
    pdf.rect(20, yPos, pageWidth - 40, 60, 'S');
    
    pdf.setTextColor(0, 0, 0);
    pdf.setFontSize(12);
    
    const resultsData = [
      [t.results.grossRevenue, formatCurrency(results.grossRevenue)],
      [t.results.netRevenue, formatCurrency(results.netRevenue)],
      [t.results.profitMargin, formatPercentage(results.profitMargin)],
      [t.results.monthlyProfit, formatCurrency(results.monthlyProfit)]
    ];
    
    let resultYPos = yPos + 12;
    resultsData.forEach(([label, value]) => {
      pdf.setFont('helvetica', 'bold');
      pdf.text(label + ':', 25, resultYPos);
      pdf.setFont('helvetica', 'bold');
      pdf.setTextColor(30, 58, 138);
      pdf.text(value, 120, resultYPos);
      pdf.setTextColor(0, 0, 0);
      resultYPos += 12;
    });
    
    // 12-Month Projection
    yPos += 80;
    pdf.setTextColor(30, 58, 138);
    pdf.setFontSize(16);
    pdf.setFont('helvetica', 'bold');
    pdf.text(language === 'en' ? '12-Month Revenue Projection' : 'Projection 12 Mois', 20, yPos);
    
    const projectionData = generateRevenueProjection(results, 12);
    yPos += 15;
    pdf.setFontSize(10);
    pdf.setFont('helvetica', 'normal');
    pdf.setTextColor(0, 0, 0);
    
    // Table headers
    pdf.setFont('helvetica', 'bold');
    pdf.text('Month', 25, yPos);
    pdf.text('Gross Revenue', 70, yPos);
    pdf.text('Net Revenue', 130, yPos);
    
    yPos += 8;
    pdf.setFont('helvetica', 'normal');
    
    projectionData.slice(0, 6).forEach((month) => {
      pdf.text(month.month, 25, yPos);
      pdf.text(formatCurrency(month.grossRevenue), 70, yPos);
      pdf.text(formatCurrency(month.netRevenue), 130, yPos);
      yPos += 6;
    });
    
    // Footer
    pdf.setFontSize(8);
    pdf.setTextColor(100, 100, 100);
    pdf.text('Generated by Storeino Revenue Simulator', 20, pageHeight - 10);
    pdf.text('www.storeino.com', pageWidth - 40, pageHeight - 10);
    
    // Save the PDF
    const fileName = `storeino-revenue-analysis-${currentDate.replace(/\//g, '-')}.pdf`;
    pdf.save(fileName);
    
    return true;
  } catch (error) {
    console.error('Error generating PDF:', error);
    return false;
  }
};